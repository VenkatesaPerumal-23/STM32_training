void SystemClock_Config(void);
static void MX_GPIO_Init(void);
extern void initialise_monitor_handles(void);

SemaphoreHandle_t xRecursiveMutex;

void safe_printf(char* string){

	xSemaphoreTakeRecursive(xRecursiveMutex,portMAX_DELAY);

	printf("%s\n",string);

	xSemaphoreGiveRecursive(xRecursiveMutex);
}

void Task1(void *argument)
{
    for (;;)
    {
        safe_printf("Task1: starting operation...\n");

        vTaskDelay(pdMS_TO_TICKS(500));

        xSemaphoreTakeRecursive(xRecursiveMutex, portMAX_DELAY);

        safe_printf("Task1: nested safe print using recursive mutex\n");

        xSemaphoreGiveRecursive(xRecursiveMutex);

    }
}

void Task2(void *argument)
{
    for (;;)
    {
        safe_printf("Task2: running periodic operation...\n");

        vTaskDelay(pdMS_TO_TICKS(500));
    }
}

int main(void)
{

  initialise_monitor_handles();

  HAL_Init();

  SystemClock_Config();

  MX_GPIO_Init();

  printf("FreeRTOS Recursive Mutex\n");

  xRecursiveMutex=xSemaphoreCreateRecursiveMutex();

  if(xRecursiveMutex==NULL){

	  printf("Failed to create it\n");
	  while(1);
  }


  /* Create two tasks */
  xTaskCreate(Task1, "Task1", 128, NULL, 2, NULL);
  xTaskCreate(Task2, "Task2", 128, NULL, 2, NULL);

  /* Start scheduler */
  vTaskStartScheduler();

  for(;;);
}

